-- =====================================================================
-- Expense Voucher Management System - initial schema (PostgreSQL)
-- =====================================================================

-- ---------- Enum types ----------
DO $$ BEGIN
  CREATE TYPE user_role AS ENUM ('EMPLOYEE', 'DIRECTOR', 'ACCOUNTS');
EXCEPTION WHEN duplicate_object THEN NULL; END $$;

DO $$ BEGIN
  CREATE TYPE voucher_status AS ENUM ('DRAFT', 'PENDING_APPROVAL', 'APPROVED', 'REJECTED');
EXCEPTION WHEN duplicate_object THEN NULL; END $$;

-- ---------- Helper: keep updated_at current ----------
CREATE OR REPLACE FUNCTION set_updated_at()
RETURNS TRIGGER AS $$
BEGIN
  NEW.updated_at = NOW();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- ---------- Signature images ----------
-- Images are stored in the database (not on disk) so the app works on hosts
-- with an ephemeral filesystem (Render, Railway, Heroku...). Rows are never
-- updated: replacing a signature inserts a new row, so a signed voucher keeps
-- pointing at exactly the image it was signed with.
CREATE TABLE IF NOT EXISTS signatures (
  id          SERIAL PRIMARY KEY,
  mime_type   VARCHAR(50)  NOT NULL,
  size_bytes  INTEGER      NOT NULL,
  data        BYTEA        NOT NULL,
  uploaded_by INTEGER,
  created_at  TIMESTAMPTZ  NOT NULL DEFAULT NOW()
);

-- ---------- Users ----------
CREATE TABLE IF NOT EXISTS users (
  id              SERIAL PRIMARY KEY,
  name            VARCHAR(100)  NOT NULL,
  email           VARCHAR(150)  NOT NULL UNIQUE,
  password_hash   VARCHAR(255)  NOT NULL,
  role            user_role     NOT NULL,
  employee_code   VARCHAR(30)   UNIQUE,
  department      VARCHAR(100),
  signature_id    INTEGER REFERENCES signatures(id),  -- saved signature (reused on vouchers)
  is_active       BOOLEAN       NOT NULL DEFAULT TRUE,
  created_at      TIMESTAMPTZ   NOT NULL DEFAULT NOW(),
  updated_at      TIMESTAMPTZ   NOT NULL DEFAULT NOW()
);

DROP TRIGGER IF EXISTS trg_users_updated_at ON users;
CREATE TRIGGER trg_users_updated_at
  BEFORE UPDATE ON users
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- ---------- Voucher number sequence ----------
-- Voucher numbers look like EV-2026-00001 and are generated by the database,
-- so they are unique even under concurrent inserts.
CREATE SEQUENCE IF NOT EXISTS voucher_number_seq START 1;

-- ---------- Vouchers ----------
CREATE TABLE IF NOT EXISTS vouchers (
  id                        SERIAL PRIMARY KEY,
  voucher_number            VARCHAR(30) NOT NULL UNIQUE
                              DEFAULT ('EV-' || TO_CHAR(NOW(), 'YYYY') || '-' ||
                                       LPAD(NEXTVAL('voucher_number_seq')::TEXT, 5, '0')),
  voucher_date              DATE          NOT NULL DEFAULT CURRENT_DATE,
  expense_date              DATE          NOT NULL,
  department                VARCHAR(100)  NOT NULL,
  expense_title             VARCHAR(150)  NOT NULL,
  expense_category          VARCHAR(50)   NOT NULL,
  expense_description       TEXT,
  amount                    NUMERIC(12,2) NOT NULL CHECK (amount > 0),

  -- employee information (snapshot at creation time)
  employee_id               INTEGER       NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
  employee_name             VARCHAR(100)  NOT NULL,
  employee_code             VARCHAR(30),
  employee_signature_id     INTEGER       REFERENCES signatures(id),

  -- approval information
  status                    voucher_status NOT NULL DEFAULT 'DRAFT',
  submitted_at              TIMESTAMPTZ,
  reviewed_by               INTEGER       REFERENCES users(id) ON DELETE RESTRICT,
  director_signature_id     INTEGER       REFERENCES signatures(id),
  approval_date             TIMESTAMPTZ,
  rejection_reason          TEXT,
  rejected_at               TIMESTAMPTZ,

  -- audit information
  created_at                TIMESTAMPTZ   NOT NULL DEFAULT NOW(),
  updated_at                TIMESTAMPTZ   NOT NULL DEFAULT NOW(),

  -- Business rules enforced at the database level as a second line of defence
  CONSTRAINT chk_submitted_has_employee_signature
    CHECK (status = 'DRAFT' OR employee_signature_id IS NOT NULL),
  CONSTRAINT chk_approved_has_director_signature
    CHECK (status <> 'APPROVED' OR (director_signature_id IS NOT NULL AND approval_date IS NOT NULL)),
  CONSTRAINT chk_rejected_has_reason
    CHECK (status <> 'REJECTED' OR (rejection_reason IS NOT NULL AND LENGTH(TRIM(rejection_reason)) > 0))
);

CREATE INDEX IF NOT EXISTS idx_vouchers_employee   ON vouchers(employee_id);
CREATE INDEX IF NOT EXISTS idx_vouchers_status     ON vouchers(status);
CREATE INDEX IF NOT EXISTS idx_vouchers_department ON vouchers(department);
CREATE INDEX IF NOT EXISTS idx_vouchers_category   ON vouchers(expense_category);
CREATE INDEX IF NOT EXISTS idx_vouchers_exp_date   ON vouchers(expense_date);

DROP TRIGGER IF EXISTS trg_vouchers_updated_at ON vouchers;
CREATE TRIGGER trg_vouchers_updated_at
  BEFORE UPDATE ON vouchers
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- ---------- Voucher activity log (audit trail) ----------
CREATE TABLE IF NOT EXISTS voucher_activity (
  id          SERIAL PRIMARY KEY,
  voucher_id  INTEGER      NOT NULL REFERENCES vouchers(id) ON DELETE CASCADE,
  action      VARCHAR(30)  NOT NULL,  -- CREATED, UPDATED, SUBMITTED, APPROVED, REJECTED
  actor_id    INTEGER      NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
  remarks     TEXT,
  created_at  TIMESTAMPTZ  NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_activity_voucher ON voucher_activity(voucher_id);
CREATE INDEX IF NOT EXISTS idx_activity_created ON voucher_activity(created_at DESC);

-- ---------- Migration bookkeeping ----------
CREATE TABLE IF NOT EXISTS schema_migrations (
  filename    VARCHAR(255) PRIMARY KEY,
  applied_at  TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
